export function themeIntro(theme: string) {
  switch (theme) {
    case 'Исекай':
      return 'Исекай — истории о героях, попавших в другой мир. В этой подборке собраны тайтлы с такой темой: выбирайте приключения, знакомьтесь с героями и открывайте карточки аниме.';
    case 'Магия':
      return 'Магические школы, заклинания и необычные способности объединяют аниме этой подборки. Здесь собраны истории с темой магии; описание и сведения о просмотре находятся в карточке каждого тайтла.';
    case 'Школа':
      return 'Школьные будни, дружба, клубы и взросление — темы этих историй. Подборка объединяет аниме со школьной тематикой, от повседневных сюжетов до фантастических приключений.';
    default:
      return `Подборка «${theme}» объединяет аниме с общей темой или мотивом истории. Ниже представлены тайтлы из каталога AniMonster; в карточках можно прочитать описание и проверить сведения о просмотре.`;
  }
}
