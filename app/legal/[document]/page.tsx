export default async function LegalPage({
  params,
}: {
  params: Promise<{ document: string }>;
}) {
  const key = (await params).document as keyof typeof documents;
  const document = documents[key];
  if (!document) notFound();
  const revisionDate = new Intl.DateTimeFormat('ru-RU', {
    dateStyle: 'long',
    timeZone: 'Europe/Moscow',
  }).format(new Date());
  const sections = document.sections();
  return (
    <div className="social-site">
      <CommunityHeader />
      <main className="title-page legal-page">
        <span className="eyebrow">ANIMONSTER / ДОКУМЕНТЫ</span>
        <h1>{document.title}</h1>
        <p className="muted">Редакция от {revisionDate}</p>
        {key === 'support' && (
          <p>
            <a className="primary" href={`mailto:${contactEmail()}`}>
              Написать в поддержку · {contactEmail()}
            </a>
          </p>
        )}
        {sections.map(([title, body]) => (
          <section className="social-panel" key={title}>
            <h2>{title}</h2>
            <p>{body}</p>
          </section>
        ))}
      </main>
    </div>
  );
}
